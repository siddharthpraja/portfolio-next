"use client";
import { useEffect, useMemo, useRef } from "react";
import { useFrame } from "@react-three/fiber";
import * as THREE from "three";
import type { Beat, Chapter } from "@/lib/story/types";
import { applyLocomotion, armGestures, basePose, dampPose, lerpAngle, targetPose, type Pose } from "@/lib/story/pose";
import { makeShadowTexture } from "./shadow";
import type { RobotPosRef, SpeakingRef } from "./shared";

// G.A.U.T.A.M. Bot: an original character built from primitives and driven by a small procedural rig.
// There is no external model file, so nothing to license or download. Animation clips are generated by
// lib/story/pose.ts (emotion + gesture -> joint angles), with blinking, breathing, walking and lip-flap on top.

const WHITE = "#f3f5f7";
const GRAPHITE = "#262a31";
const BLUE = "#3f7bbd";
const CYAN = "#58e6ff";

type Props = {
  beat: Beat;
  chapter: Chapter;
  /** Changes whenever the beat restarts, so gestures start from t = 0. */
  seq: number;
  speaking: SpeakingRef;
  posRef: RobotPosRef;
  reduced: boolean;
};

export function Robot({ beat, chapter, seq, speaking, posRef, reduced }: Props) {
  const root = useRef<THREE.Group>(null);
  const body = useRef<THREE.Group>(null);
  const head = useRef<THREE.Group>(null);
  const armA = useRef<THREE.Group>(null);
  const armB = useRef<THREE.Group>(null);
  const legA = useRef<THREE.Group>(null);
  const legB = useRef<THREE.Group>(null);
  const eyeA = useRef<THREE.Mesh>(null);
  const eyeB = useRef<THREE.Mesh>(null);
  const browA = useRef<THREE.Mesh>(null);
  const browB = useRef<THREE.Mesh>(null);
  const mouth = useRef<THREE.Mesh>(null);
  const chest = useRef<THREE.Mesh>(null);
  const shadow = useRef<THREE.Mesh>(null);

  const pose = useRef<Pose>({ ...basePose });
  const gestureT = useRef(0);
  const yaw = useRef(0);
  const phase = useRef(0);
  const blink = useRef({ next: 2.5, t: -1 });
  const clock = useRef(0);
  const beatRef = useRef(beat);

  const shadowTex = useMemo(() => makeShadowTexture(), []);
  const eyeMat = useMemo(() => new THREE.MeshBasicMaterial({ color: CYAN, toneMapped: false }), []);
  const browMat = useMemo(() => new THREE.MeshBasicMaterial({ color: "#2fb8d6", toneMapped: false }), []);
  const bodyMat = useMemo(
    () => new THREE.MeshPhysicalMaterial({ color: WHITE, roughness: 0.28, metalness: 0.04, clearcoat: 0.8, clearcoatRoughness: 0.2 }),
    [],
  );
  const jointMat = useMemo(() => new THREE.MeshStandardMaterial({ color: GRAPHITE, roughness: 0.5, metalness: 0.6 }), []);
  const blueMat = useMemo(() => new THREE.MeshStandardMaterial({ color: BLUE, roughness: 0.35, metalness: 0.8 }), []);
  const visorMat = useMemo(() => new THREE.MeshStandardMaterial({ color: "#0a111a", roughness: 0.12, metalness: 0.7 }), []);
  const chestMat = useMemo(() => new THREE.MeshBasicMaterial({ color: CYAN, toneMapped: false }), []);

  useEffect(() => () => {
    [shadowTex, eyeMat, browMat, bodyMat, jointMat, blueMat, visorMat, chestMat].forEach((x) => x.dispose());
  }, [shadowTex, eyeMat, browMat, bodyMat, jointMat, blueMat, visorMat, chestMat]);

  // New chapter: snap to the chapter's start position.
  useEffect(() => {
    posRef.current = { x: chapter.start[0], z: chapter.start[1] };
    if (root.current) root.current.position.set(chapter.start[0], 0, chapter.start[1]);
    yaw.current = 0;
  }, [chapter, posRef]);

  // New beat: restart the gesture clock.
  useEffect(() => { beatRef.current = beat; gestureT.current = 0; }, [beat, seq]);

  useFrame((state, rawDt) => {
    const dt = Math.min(rawDt, 0.05);
    const b = beatRef.current;
    const m = reduced ? 0 : 1;
    clock.current += dt;
    gestureT.current += dt;
    const r = root.current; if (!r) return;

    // Movement towards beat.at
    let moving = false;
    let moveYaw = yaw.current;
    if (b.at) {
      const dx = b.at[0] - posRef.current.x, dz = b.at[1] - posRef.current.z;
      const dist = Math.hypot(dx, dz);
      if (dist > 0.06) {
        moving = true;
        const speed = (b.run ? 3.8 : 1.7) * (reduced ? 3 : 1);
        const step = Math.min(dist, speed * dt);
        posRef.current.x += (dx / dist) * step;
        posRef.current.z += (dz / dist) * step;
        phase.current += step * (b.run ? 4.2 : 5.2);
        moveYaw = Math.atan2(dx, dz);
      }
    }
    r.position.x = posRef.current.x;
    r.position.z = posRef.current.z;

    // Facing: movement direction, else the pointing target, else the camera.
    let desiredYaw = 0;
    if (moving) desiredYaw = moveYaw;
    else if (b.gesture === "point" && b.target) desiredYaw = Math.atan2(b.target[0] - posRef.current.x, b.target[2] - posRef.current.z) * 0.85;
    yaw.current = lerpAngle(yaw.current, desiredYaw, 1 - Math.exp(-(reduced ? 30 : 6) * dt));
    r.rotation.y = yaw.current;

    // Pose = emotion + gesture (+ locomotion), damped.
    let tgt = targetPose(b.emotion, moving ? "idle" : b.gesture, gestureT.current, m);
    if (moving) tgt = applyLocomotion(tgt, phase.current, !!b.run, !armGestures.includes(b.gesture));
    // Keep the head on the camera while the body turns.
    tgt.headYaw -= yaw.current * 0.6;
    dampPose(pose.current, tgt, dt, reduced ? 40 : 9);
    const p = pose.current;

    // Blinking
    const bl = blink.current;
    bl.next -= dt;
    if (bl.next <= 0 && bl.t < 0 && b.emotion !== "sleep" && !reduced) { bl.t = 0; bl.next = 2.5 + Math.random() * 3; }
    let blinkScale = 1;
    if (bl.t >= 0) { bl.t += dt; blinkScale = 1 - Math.sin(Math.min(1, bl.t / 0.16) * Math.PI) * 0.92; if (bl.t > 0.16) bl.t = -1; }

    // Speaking: lip-flap, chest pulse, tiny nods.
    const talk = speaking.current;
    const flap = talk ? 0.5 + 0.5 * Math.sin(clock.current * 18) * Math.sin(clock.current * 7.3 + 1) : 0;
    const breathe = Math.sin(clock.current * 1.8) * 0.012 * (reduced ? 0.3 : 1);
    const shake = p.shake ? (Math.random() - 0.5) * p.shake : 0;

    if (body.current) {
      body.current.position.y = p.bodyY + breathe;
      body.current.position.x = shake;
      body.current.rotation.x = p.lean;
      body.current.rotation.z = p.roll;
      body.current.scale.set(1, 1 + breathe * 2, 1);
    }
    if (head.current) {
      head.current.rotation.set(p.headPitch + (talk && !reduced ? flap * 0.04 : 0), p.headYaw, p.headRoll);
    }
    if (armA.current) armA.current.rotation.set(p.aAx, 0, p.aAz);
    if (armB.current) armB.current.rotation.set(p.aBx, 0, p.aBz);
    // When sitting, the legs lower with the body so the robot rests on the floor.
    const hipY = 0.36 + Math.min(0, p.bodyY);
    if (legA.current) { legA.current.rotation.x = p.legA; legA.current.position.y = hipY; }
    if (legB.current) { legB.current.rotation.x = p.legB; legB.current.position.y = hipY; }

    const eh = Math.max(0.04, p.eyeH * blinkScale);
    if (eyeA.current) eyeA.current.scale.set(p.eyeW, eh, 1);
    if (eyeB.current) eyeB.current.scale.set(p.eyeW, eh, 1);
    eyeMat.color.setRGB(0.35 * p.glow, 0.9 * p.glow, 1.0 * p.glow);
    if (browA.current) { browA.current.position.y = 0.26 + p.browAy; browA.current.rotation.z = p.browAr; }
    if (browB.current) { browB.current.position.y = 0.26 + p.browBy; browB.current.rotation.z = -p.browBr; }
    if (mouth.current) {
      const smile = b.emotion === "happy" || b.emotion === "laugh" || b.emotion === "proud" ? 1.25 : b.emotion === "nervous" ? 0.7 : 1;
      mouth.current.scale.set(smile, 0.6 + flap * 5 + (b.emotion === "surprised" ? 3 : 0) + (b.emotion === "laugh" ? 2.5 : 0), 1);
      mouth.current.visible = b.emotion !== "sleep";
    }
    if (chest.current) {
      const pulse = 0.75 + 0.25 * Math.sin(clock.current * 3) + (talk ? flap * 0.4 : 0);
      chest.current.scale.setScalar(0.9 + pulse * 0.2);
      chestMat.color.setRGB(0.3 * pulse * p.glow, 0.85 * pulse * p.glow, 1 * pulse * p.glow);
    }
    if (shadow.current) {
      const s = 1.5 - p.bodyY * 1.2;
      shadow.current.scale.set(s, s, 1);
      (shadow.current.material as THREE.MeshBasicMaterial).opacity = 0.55 - p.bodyY * 0.6;
    }
  });

  return (
    <group ref={root}>
      {/* contact shadow (a texture, so no shadow maps are needed on phones) */}
      <mesh ref={shadow} rotation={[-Math.PI / 2, 0, 0]} position={[0, 0.012, 0]}>
        <planeGeometry args={[1.4, 1.4]} />
        <meshBasicMaterial map={shadowTex} transparent opacity={0.55} depthWrite={false} />
      </mesh>

      {/* legs */}
      {([[0.18, legA], [-0.18, legB]] as const).map(([x, ref], i) => (
        <group key={i} ref={ref} position={[x, 0.36, 0]}>
          <mesh position={[0, -0.12, 0]} material={jointMat}><capsuleGeometry args={[0.07, 0.1, 4, 10]} /></mesh>
          <mesh position={[0, -0.27, 0.05]} scale={[1, 0.55, 1.5]} material={bodyMat}><sphereGeometry args={[0.13, 16, 12]} /></mesh>
          <mesh position={[0, -0.33, 0.04]} scale={[1.05, 0.18, 1.55]} material={blueMat}><sphereGeometry args={[0.13, 12, 8]} /></mesh>
        </group>
      ))}

      <group ref={body} position={[0, 0, 0]}>
        {/* torso */}
        <mesh position={[0, 0.72, 0]} scale={[1, 1.05, 0.9]} material={bodyMat}><sphereGeometry args={[0.4, 32, 24]} /></mesh>
        <mesh position={[0, 0.42, 0]} scale={[1, 0.25, 0.9]} material={jointMat}><sphereGeometry args={[0.31, 16, 10]} /></mesh>
        {/* chest light */}
        <mesh ref={chest} position={[0, 0.74, 0.355]} material={chestMat}><circleGeometry args={[0.075, 24]} /></mesh>
        <mesh position={[0, 0.74, 0.35]} material={jointMat}><ringGeometry args={[0.078, 0.108, 24]} /></mesh>

        {/* arms */}
        {([[0.46, armA], [-0.46, armB]] as const).map(([x, ref], i) => (
          <group key={i} ref={ref} position={[x, 0.95, 0]}>
            <mesh material={jointMat}><sphereGeometry args={[0.085, 12, 10]} /></mesh>
            <mesh position={[0, -0.17, 0]} material={bodyMat}><capsuleGeometry args={[0.07, 0.17, 4, 10]} /></mesh>
            <mesh position={[0, -0.37, 0]} material={blueMat}><sphereGeometry args={[0.095, 14, 10]} /></mesh>
          </group>
        ))}

        {/* neck + head */}
        <mesh position={[0, 1.05, 0]} material={jointMat}><cylinderGeometry args={[0.1, 0.13, 0.12, 16]} /></mesh>
        <group ref={head} position={[0, 1.5, 0]}>
          <mesh scale={[1.12, 0.94, 1]} material={bodyMat}><sphereGeometry args={[0.5, 40, 30]} /></mesh>
          {/* ear discs */}
          {[0.54, -0.54].map((x) => (
            <mesh key={x} position={[x, 0, 0]} rotation={[0, 0, Math.PI / 2]} material={blueMat}><cylinderGeometry args={[0.13, 0.13, 0.1, 20]} /></mesh>
          ))}
          {/* visor */}
          <mesh position={[0, 0.02, 0.27]} scale={[0.95, 0.7, 0.62]} material={visorMat}><sphereGeometry args={[0.5, 32, 24]} /></mesh>
          {/* eyes */}
          <mesh ref={eyeA} position={[0.2, 0.08, 0.545]} material={eyeMat}><capsuleGeometry args={[0.07, 0.1, 4, 12]} /></mesh>
          <mesh ref={eyeB} position={[-0.2, 0.08, 0.545]} material={eyeMat}><capsuleGeometry args={[0.07, 0.1, 4, 12]} /></mesh>
          {/* brows (y is set per frame) */}
          <mesh ref={browA} position={[0.2, 0.26, 0.5]} material={browMat}><boxGeometry args={[0.15, 0.028, 0.02]} /></mesh>
          <mesh ref={browB} position={[-0.2, 0.26, 0.5]} material={browMat}><boxGeometry args={[0.15, 0.028, 0.02]} /></mesh>
          {/* mouth */}
          <mesh ref={mouth} position={[0, -0.14, 0.555]} material={eyeMat}><boxGeometry args={[0.15, 0.02, 0.012]} /></mesh>
        </group>
      </group>
    </group>
  );
}
